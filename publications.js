function publicationUrl(file) {
  return encodeURI(file);
}

function previewUrl(file) {
  return encodeURI(file);
}

function previewFallbackMarkup(item) {
  return `<div class="paper-preview generated-preview"><span>${escapeHtml(item.year)}</span><strong>${escapeHtml(item.type.toUpperCase())}</strong><p>${escapeHtml(item.title)}</p></div>`;
}

function publicationSlug(title) {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 90)
    .replace(/-+$/g, "");
}

function absoluteUrl(path) {
  return new URL(encodeURI(path), window.location.href).href;
}

